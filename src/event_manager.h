#pragma once
#include <Arduino.h>
// =====================================================
// Event Manager
// 系统事件管理模块
// 作用：
// 统一管理各模块产生的事件
// 模块之间不要直接调用
// =====================================================

// ==========================
// 系统事件定义
// ==========================

enum SystemEvent
{
    // 无事件
    EVENT_NONE = 0,

    // ======================
    // WiFi事件
    // ======================

    EVENT_WIFI_CONNECTED,

    EVENT_WIFI_DISCONNECTED,

    // ======================
    // 时间事件
    // ======================

    EVENT_NTP_SYNC_OK,

    EVENT_TIME_INVALID,

    // ======================
    // 配置事件
    // ======================

    EVENT_CONFIG_CHANGED,

    // ======================
    // 传感器事件
    // ======================

    EVENT_WEIGHT_ERROR,

    // ======================
    // 系统事件
    // ======================

    EVENT_SYSTEM_ERROR
};

// ==========================
// 初始化
// ==========================

void event_manager_init();

// ==========================
// 发送事件
//
// 模块调用
//
// 例如：
//
// event_push(
// EVENT_WIFI_CONNECTED
// );
//
// ==========================

void event_push(
    SystemEvent event
);

// ==========================
// 查询事件
//
// 查询后不会自动删除
//
// ==========================

bool event_available(
    SystemEvent event
);

// ==========================
// 获取并清除事件
//
// 推荐使用
//
// ==========================

bool event_get(
    SystemEvent event
);

// ==========================
// 清除指定事件
// ==========================

void event_clear(
    SystemEvent event
);