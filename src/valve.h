#ifndef VALVE_H
#define VALVE_H

#include <Arduino.h>
// =====================================================
// Valve 模块 - GPIO 控制
// 高电平有效（active_level = 1）
// =====================================================
// =====================================================
// 初始化
// =====================================================
void valve_init();
// =====================================================
// 打开阀门
// 返回 true 表示成功，false 表示失败
// =====================================================
bool valve_open();
// =====================================================
// 关闭阀门
// 返回 true 表示成功，false 表示失败
// =====================================================
bool valve_close();
// =====================================================
// 切换阀门状态
// =====================================================
bool valve_toggle();
// =====================================================
// 获取当前状态
// =====================================================
bool valve_is_open();
// =====================================================
// 获取引脚号（调试用）
// =====================================================
int valve_get_pin();
// =====================================================
// Task 函数（loop 中调用）
// 处理安全超时检测
// =====================================================
void valve_task();

bool valve_force_close();

#endif